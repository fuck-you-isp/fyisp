// slowdown is the synthetic "evening slowdown": these targets run slower
// than their normal for the last 45 minutes of the backfill and live.
var slowdown = map[string]float64{"AWS-us-east-1": 2.4, "dev-GitHub": 1.8, "Discord": 1.6}

const slowFor = 45 * time.Minute

// slowSink multiplies the RTT of the slowdown targets from `since` on.
func slowSink(inner model.Sink, since time.Time) model.Sink {
	return model.SinkFunc(func(s model.Sample) {
		if f, ok := slowdown[s.Key.Target]; ok && !s.Lost && !s.Slot.Before(since) {
			s.RTT = time.Duration(float64(s.RTT) * f)
		}
		inner.Observe(s)
	})
}

// ---------- annotations ----------

// fakeNotes implements web.AnnotationStore in memory.
type fakeNotes struct {
	mu   sync.Mutex
	next int64
	m    map[int64]model.Annotation
}

func newFakeNotes(now time.Time, bf time.Duration) *fakeNotes {
	f := &fakeNotes{m: map[int64]model.Annotation{}}
	ctx := context.Background()
	add := func(at, end time.Time, text string, public bool) {
		_ = f.AddAnnotation(ctx, &model.Annotation{At: at, End: end, Text: text, Public: public})
	}
	add(now.Add(-slowFor), time.Time{}, "Evenings are slow again: GitHub pushes crawl", true)
	add(now.Add(-6*time.Minute), time.Time{}, "Zoom call with the team froze twice", false)
	if bf > 0 {
		_, isp, lan := windows(bf, now)
		add(isp.from.Add(time.Minute), time.Time{}, "Video call dropped (client demo)", false)
		add(isp.from, isp.to.Add(10*time.Minute), "ISP ticket #4471 opened; they blame \"maintenance\"", true)
		add(lan.from, time.Time{}, "Rebooted the router in the hallway", false)
	}
	return f
}

func (f *fakeNotes) AddAnnotation(_ context.Context, a *model.Annotation) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.next++
	now := time.Now()
	a.ID, a.Created, a.Updated = f.next, now, now
	f.m[a.ID] = *a
	return nil
}

func (f *fakeNotes) UpdateAnnotation(_ context.Context, a *model.Annotation) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	old, ok := f.m[a.ID]
	if !ok {
		return web.ErrNotFound
	}
	a.Created, a.Updated = old.Created, time.Now()
	f.m[a.ID] = *a
	return nil
}

func (f *fakeNotes) DeleteAnnotation(_ context.Context, id int64) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	if _, ok := f.m[id]; !ok {
		return web.ErrNotFound
	}
	delete(f.m, id)
	return nil
}

func (f *fakeNotes) Annotations(_ context.Context, from, to time.Time, publicOnly bool) ([]model.Annotation, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	var out []model.Annotation
	for _, a := range f.m {
		end := a.End
		if end.IsZero() {
			end = a.At
		}
		if a.At.After(to) || end.Before(from) || (publicOnly && !a.Public) {
			continue
		}
		out = append(out, a)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].At.Before(out[j].At) })
	return out, nil
}

