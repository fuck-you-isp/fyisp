// fakeReports implements web.ReportSource: a stub builder (a small
// self-contained HTML page like the real report: inline CSS and SVG, no
// scripts) and an in-memory snapshot store.
type fakeReports struct {
	notes *fakeNotes
	inc   web.VerdictSource
	st    store.Reader

	mu   sync.Mutex
	m    map[string]model.ReportMeta
	body map[string][]byte
}

func newFakeReports(notes *fakeNotes, inc web.VerdictSource, st store.Reader) *fakeReports {
	return &fakeReports{notes: notes, inc: inc, st: st, m: map[string]model.ReportMeta{}, body: map[string][]byte{}}
}

func (f *fakeReports) Build(ctx context.Context, o web.ReportOptions) ([]byte, error) {
	var b strings.Builder
	esc := html.EscapeString
	tf := func(t time.Time) string { return t.Local().Format("Jan 2 15:04") }
	fmt.Fprintf(&b, `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>%s</title>
<style>
:root{color-scheme:light dark;--ink:#0b0b0b;--muted:#6f6e69;--bg:#fcfcfb;--line:#e1e0d9;--acc:#2a78d6;--bad:#cc2f2f}
@media (prefers-color-scheme:dark){:root{--ink:#fff;--muted:#898781;--bg:#1a1a19;--line:#2c2c2a;--acc:#3987e5;--bad:#e04848}}
body{margin:0 auto;max-width:880px;padding:24px 16px;font:14px/1.5 system-ui,sans-serif;color:var(--ink);background:var(--bg)}
h1{font-size:22px;margin:0 0 4px}h2{font-size:16px;margin:24px 0 8px;border-bottom:1px solid var(--line);padding-bottom:4px}
.m{color:var(--muted)}table{border-collapse:collapse;width:100%%}td,th{text-align:left;padding:4px 8px;border-bottom:1px solid var(--line)}
.tag{display:inline-block;font-size:11px;padding:0 8px;border-radius:9px;border:1px solid var(--line)}svg{width:100%%;height:auto}
</style></head><body>`, esc(o.Title))
	fmt.Fprintf(&b, `<h1>%s</h1><p class="m">%s – %s · generated by fyisp-webdev (sample report) · %s</p>`,
		esc(o.Title), tf(o.From), tf(o.To), map[bool]string{true: "redacted: no private addresses, public notes only", false: "includes private details"}[o.Redact])
	b.WriteString(`<h2>Outages</h2><table><tr><th>When</th><th>Kind</th><th>What happened</th><th>Peak loss</th></tr>`)
	var list []model.Incident
	if f.inc != nil {
		list, _ = f.inc.Incidents(ctx, o.From, o.To)
	}
	if len(list) == 0 {
		b.WriteString(`<tr><td colspan="4" class="m">No incidents in this range.</td></tr>`)
	}
	for _, in := range list {
		end := "ongoing"
		if !in.End.IsZero() {
			end = in.End.Local().Format("15:04")
		}
		fmt.Fprintf(&b, `<tr><td>%s – %s</td><td><span class="tag">%s</span></td><td>%s</td><td>%.0f%%</td></tr>`,
			tf(in.Start), end, esc(string(in.Kind)), esc(in.Summary), in.PeakLoss*100)
	}
	b.WriteString(`</table><h2>Latency (AWS-us-east-1, HTTPS)</h2>`)
	b.WriteString(f.sparkline(ctx, o.From, o.To))
	b.WriteString(`<h2>Notes</h2><ul>`)
	notes, _ := f.notes.Annotations(ctx, o.From, o.To, o.Redact)
	if len(notes) == 0 {
		b.WriteString(`<li class="m">No notes in this range.</li>`)
	}
	for _, n := range notes {
		fmt.Fprintf(&b, `<li>%s — %s</li>`, tf(n.At), esc(n.Text))
	}
	b.WriteString(`</ul>`)
	if !o.Redact {
		b.WriteString(`<h2>Network details</h2><p>Gateway 192.168.1.1 · ISP edge 96.120.88.105 (po-305-1210-rur01.fremont.ca.sfba.comcast.net)</p>`)
	}
	b.WriteString(`</body></html>`)
	return []byte(b.String()), nil
}

// sparkline draws one series as an inline SVG polyline.
func (f *fakeReports) sparkline(ctx context.Context, from, to time.Time) string {
	res, err := f.st.Panel(ctx, store.PanelQuery{Keys: []model.SeriesKey{{Target: "AWS-us-east-1", Kind: model.KindHTTPS}}, From: from, To: to, MaxPoints: 300})
	if err != nil || len(res.Series) == 0 {
		return `<p class="m">No data.</p>`
	}
	m := res.Series[0].Mean
	hi := 1.0
	for _, v := range m {
		if !math.IsNaN(float64(v)) {
			hi = math.Max(hi, float64(v))
		}
	}
	var pts []string
	for i, v := range m {
		if math.IsNaN(float64(v)) {
			continue
		}
		x := 800 * float64(i) / math.Max(1, float64(len(m)-1))
		pts = append(pts, fmt.Sprintf("%.1f,%.1f", x, 150-140*float64(v)/hi))
	}
	return fmt.Sprintf(`<svg viewBox="0 0 800 160" role="img" aria-label="latency"><rect width="800" height="160" fill="none" stroke="currentColor" stroke-opacity=".15"/><polyline fill="none" stroke="#3987e5" stroke-width="1.5" points="%s"/><text x="4" y="14" font-size="11" fill="currentColor" opacity=".6">%.0f ms</text></svg>`, strings.Join(pts, " "), hi)
}

func (f *fakeReports) SaveReport(_ context.Context, m model.ReportMeta, body []byte) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.m[m.ID], f.body[m.ID] = m, body
	return nil
}

func (f *fakeReports) Report(_ context.Context, id string) (model.ReportMeta, []byte, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	m, ok := f.m[id]
	if !ok {
		return m, nil, web.ErrNotFound
	}
	return m, f.body[id], nil
}

func (f *fakeReports) Reports(context.Context) ([]model.ReportMeta, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	out := make([]model.ReportMeta, 0, len(f.m))
	for _, m := range f.m {
		out = append(out, m)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Created.After(out[j].Created) })
	return out, nil
}

func (f *fakeReports) SetReportPublic(_ context.Context, id string, public bool) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	m, ok := f.m[id]
	if !ok {
		return web.ErrNotFound
	}
	m.Public = public
	f.m[id] = m
	return nil
}

func (f *fakeReports) DeleteReport(_ context.Context, id string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	if _, ok := f.m[id]; !ok {
		return web.ErrNotFound
	}
	delete(f.m, id)
	delete(f.body, id)
	return nil
}

// seed stores a sample redacted report with a fixed ID (so its public
// link is stable across restarts with the same -secret).
func (f *fakeReports) seed(ctx context.Context, from, to time.Time) (string, error) {
	const id = "rsamplesampleaaaaaaaaaaaaa"
	body, err := f.Build(ctx, web.ReportOptions{From: from, To: to, Title: "ISP outage evidence (sample)", Redact: true})
	if err != nil {
		return "", err
	}
	return id, f.SaveReport(ctx, model.ReportMeta{ID: id, Title: "ISP outage evidence (sample)", From: from, To: to,
		Created: time.Now().Add(-time.Hour), Public: true, Bytes: len(body)}, body)
}

